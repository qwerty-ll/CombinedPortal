def ask(client, message, history=None):
    r = client.post("/api/v1/chat", json={"message": message, "history": history or []}, headers=CSRF)
    assert r.status_code == 200, r.text
    data = r.json()
    return data["reply"], [a["label"] for a in data["actions"]]


